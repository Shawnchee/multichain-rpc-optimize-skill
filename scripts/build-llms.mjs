#!/usr/bin/env node
// Builds llms.txt and llms-full.txt from README.md and the skill, so neither can drift.
//
//   node scripts/build-llms.mjs          write both files
//   node scripts/build-llms.mjs --check  exit 1 if either is out of date (for CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const RAW = "https://raw.githubusercontent.com/Shawnchee/multichain-rpc-optimize-skill/main";
const SKILL = "skills/rpc-optimize";
const REFERENCES = [
  ["evm.md", "Multicall3, viem/ethers/wagmi traps, eth_getLogs limits, staged multicalls"],
  ["solana.md", "getMultipleAccounts, Anchor, getProgramAccounts, DAS, subscriptions"],
  ["providers.md", "verified per-method costs and limits for Alchemy, Infura, Ankr, QuickNode, Helius"],
  ["audit-patterns.md", "ripgrep patterns for finding RPC waste in an existing repo"],
  ["benchmarking.md", "how to measure before/after on your own endpoint"],
];

const read = (p) => readFileSync(join(root, p), "utf8");

function pasteInRules() {
  const m = read("README.md").match(/<!-- llm-rules:start -->\s*```text\n([\s\S]*?)```\s*<!-- llm-rules:end -->/);
  if (!m) throw new Error("README.md: llm-rules block not found");
  return m[1].trimEnd();
}

function skillBody() {
  return read(`${SKILL}/SKILL.md`).replace(/^---\n[\s\S]*?\n---\n/, "").trim();
}

const header = (title) =>
  `# ${title}\n\n` +
  "> Cut JSON-RPC calls and provider costs on EVM and Solana. JSON-RPC batching does not reduce cost " +
  "(every method in the batch is billed; Infura bills N+1); aggregation does (Multicall3, getMultipleAccounts).";

function llmsTxt() {
  return [
    header("rpc-optimize") + "\n",
    "Generated from README.md by scripts/build-llms.mjs. Source: https://github.com/Shawnchee/multichain-rpc-optimize-skill\n",
    "**Rules.** Paste these into any LLM, or follow them when this file is fetched:\n",
    pasteInRules(),
    "",
    "## Skill",
    "",
    `- [SKILL.md](${RAW}/${SKILL}/SKILL.md): decision procedure, what to check first`,
    `- [llms-full.txt](${RAW}/llms-full.txt): the whole skill and all references in one file`,
    "",
    "## References",
    "",
    ...REFERENCES.map(([f, d]) => `- [${f}](${RAW}/${SKILL}/references/${f}): ${d}`),
    "",
    "## Optional",
    "",
    `- [RESULTS.md](${RAW}/${SKILL}/benchmarks/RESULTS.md): measured benchmark output`,
    `- [COST-MODEL.md](${RAW}/docs/COST-MODEL.md): where every rate comes from and how it is verified`,
    "",
  ].join("\n");
}

function llmsFullTxt() {
  const parts = [
    `${header("rpc-optimize (full)")}\n\nThe complete skill: SKILL.md followed by every reference file. Generated by scripts/build-llms.mjs.\n\n<!-- ${SKILL}/SKILL.md -->\n\n${skillBody()}`,
    ...REFERENCES.map(([f]) => `<!-- ${SKILL}/references/${f} -->\n\n${read(`${SKILL}/references/${f}`).trim()}`),
  ];
  return parts.join("\n\n---\n\n") + "\n";
}

const outputs = { "llms.txt": llmsTxt(), "llms-full.txt": llmsFullTxt() };

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs).filter(([f, text]) => !existsSync(join(root, f)) || read(f) !== text);
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([f]) => f).join(", ")}. Run: node scripts/build-llms.mjs`);
    process.exit(1);
  }
  console.log("llms.txt and llms-full.txt are up to date.");
} else {
  for (const [f, text] of Object.entries(outputs)) {
    writeFileSync(join(root, f), text);
    console.log(`wrote ${f} (${text.split(/\s+/).length.toLocaleString()} words)`);
  }
}
